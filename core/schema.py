# ---------------- 访问器 ----------------

def get_field(name: str) -> dict:
    if name not in FIELDS:
        raise KeyError(f"未知数据字段: {name!r}")
    return FIELDS[name]


def fields_by_method(method: str) -> list[str]:
    """按取数方式（AUTO/DERIVED/MANUAL）列出字段。"""
    return [k for k, v in FIELDS.items() if v["取数方式"] == method]


def method_of(name: str) -> str:
    return get_field(name)["取数方式"]


def validate_against_theses() -> dict[str, list[str]]:
    """交叉校验：**论点库**判定所需的字段是否都在此定义。

    论点库是"该查哪些数据"的唯一权威（DESIGN §7.3）——摸底取数走的正是
    `thesis.required_fields()`，这里缺定义会直接导致对应论点永不触发。
    """
    from . import thesis as th

    used = set(th.required_fields())
    return {"缺定义": sorted(used - set(FIELDS)),
            "论点库未用到": sorted(set(FIELDS) - used)}


