"""writer：论述生成（第二个 LLM 环节）。

输入：pipeline 产出的"带数据论证计划"（每条逻辑 + 真实数据 + 缺口）。
输出：每条逻辑的 { 论述文字, 图表规格(画什么，非画图本身), 加粗结论 } + 核心结论。

防幻觉铁律（贯穿设计）：
  - 只能用喂进来的真实数字，绝不编造；
  - "缺失数据"字段不得臆造数值，可定性带过或标"（数据待补）"；
  - writer 只产内容与图表规格，真正画图/排版是 renderer 的事。

核心结论最后综合各逻辑生成（DESIGN §4：印在最上但最后写）。
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field as dfield

from llm.client import DeepSeekClient

from .pipeline import MarketAnalysis

# 从研报原文里挑出可引用的数字（带单位，避免把年份、序号也算进去）
_NUMS = re.compile(r"-?\d+(?:\.\d+)?\s*(?:%|倍|万亿韩元|亿韩元|万亿元|亿元|万元|亿|元|pct|bp|个百分点)")


@dataclass
class LogicContent:
    逻辑id: str
    论述: str
    结论: str
    # 一条逻辑可配 1~3 张图，而非固定一张。此前每条逻辑写死一张图，
    # 遇到"背离类"论点（价格 vs 资金）等本就需要两个不同角度才能说清的场景，
    # 只能挤进一张图或舍弃一个角度；现在允许多张图各自支撑论述的不同部分。
    图表规格列表: list[dict] = dfield(default_factory=list)


@dataclass
class ReportContent:
    主题: str
    类型: str
    核心结论: str = ""
    推荐方向: str = ""
    logics: list[LogicContent] = dfield(default_factory=list)
    空缺逻辑: list[str] = dfield(default_factory=list)   # 论述为空/漏写的逻辑，须重试或人工补
    tokens: int = 0
    ok: bool = False
    error: str = ""


_SYSTEM = """你是场外衍生品投资策略研报的"撰稿器"。根据论证计划与【真实数据】，为每条逻辑撰写论述与图表规格。
铁律：
1. 只能使用"可用数据"里给出的真实数字；绝对不得编造、估算或引用任何未给出的数字。
2. "缺失数据"的字段表示数据待补——不要为其臆造数值，**也不得把缺失字段当作论据去支撑任何结论**
   （例如资金流数据缺失时，不可写"资金逆势流入验证修复动能"）；应写明"（数据待补）"并保持中性。
2.1 **证伪义务（重要）**：给定的"具体论点"只是**待检验的假设**，不是既定结论。
   若真实数据与论点相悖——例如论点称"估值处历史低分位"而 PB 高达 22 倍，
   或论点称"分红改善"而现金分红为 0——必须**如实指出该逻辑当前不成立或需存疑**，
   禁止圆场、淡化或强行自洽。宁可写"数据不支持这一判断"，也不要写出与数据矛盾的论断。
   此时"结论"一句应写成中性或否定，而非照搬论点。
3. 论述专业、贴合场外衍生品策略研报口吻。**所有数据值已格式化为最终可读形式，
   请原样引用，不得再做任何换算、改写或改变量级。**
3.0 **不得把精确值改写成约数或区间。** 真值是"折价 22.5%"就写 22.5%，
   不许写成"超过20%""约两成""逾20%"。这类改写看似无害，实则有两处代价：
   ①校验器按真值逐个回指，改写后的数字对不上，会被标为可疑待复核；
   ②研报的说服力正来自精确——"22.5%"是测算结果，"超过20%"是印象。
3.0.1 **也不得自己算差值、比值、涨跌幅**——只能引用已给出的数字。
   两个值都给了也不行：29.87 与 23.21 不许写成"相差逾6倍"。
   这既是编造（6 不在任何字段里），又是**表述错误**——
   在投研语境里"相差6倍"指 6 倍数关系，而实际只差 6.66 个单位，意思完全不同。
   要表达差距就并列两个真值（"当前 29.87 倍 vs FY1 预测 23.21 倍"），
   或引用已给出的折价字段；**没给折价值就不要自己算**。
3.1 **每条论述 120~200 字，要有完整论证链条**，不要只摆一两个数字就收尾。参考结构：
   现象（发生了什么）→ 反证或佐证（其它数据是否支持）→ 归因（为什么会这样）
   → 推论（对后市/配置意味着什么）。
   范例口吻："板块被减持力度排名靠前、股价跌幅较大——但基本面并未同步恶化。
   中报预告高增、PB 仅 1.37 倍（约 27% 分位），盈利改善尚未充分定价。
   减持导致的被动卖盘是股价下行的主因，而非基本面恶化；减持趋近尾声后，
   股价存在向基本面均值回归的动力。"
3.1.1 **首次提到板块时必须写全称，之后才可简称"板块"。**
   实测成品通篇写"近期板块年化波动率攀升至76.0%""板块归母净利同比13.75%"，
   **从头到尾没说这是哪个板块**——读者不知道在分析什么。
   第一句应写成"电子元件板块近期年化波动率攀升至76.0%"。
   代表标的同理：首次出现写"以工业富联为代表"，不要只写"代表标的"。
3.1.2 **提到主题之外的公司、产品或机构时，须用一个从句交代它与本主题的关系。**
   实测有一条逻辑标题是"长鑫市占率破7%"，正文直接展开长鑫，
   而读者并不知道长鑫是谁、与引发本次需求的 SK 海力士是什么关系。
   应写成"国产存储厂商长鑫（SK海力士在通用 DRAM 的直接竞争者）市占率突破 7%…"。
   一句话说清"它是什么、与本主题什么关系"即可，不要展开介绍。
3.2 **"板块全景数据"里的字段可以引用**，用来把论证写厚（如讲估值时带上 PB 与分位、
   讲盈利时带上 ROE 与分红率）。但**不得偏离本条论点**去讲别的主题——
   全景数据是用来支撑本条论证的，不是让你把所有数字堆一遍。
3.3 有"成分股明细"时，**善用个股举例说明板块内部分化**
   （如"中信 +54.6%、中信建投 +99.0%，而国泰海通 -47.8%，板块内部盈利分化明显"）。
   这比只给一个聚合数字更有说服力。
3.4 **有"子行业明细"时，说明本板块是宽口径合并的，且论述必须覆盖到各子行业，
   不得只讲其中市值最大的那一个。** 这类板块（消费/大消费等）由若干一级行业合并而成，
   前几大成分股按市值排下来往往集中在同一个子行业（如消费板块前几大清一色白酒），
   只顺着它们写，成品就成了"标题写消费、内容全是白酒"的以偏概全。
   至少要点出各子行业之间的差异（谁强谁弱、估值与盈利是否背离），
   首次提及板块时并说明口径（如"消费板块（食品饮料、家用电器、商贸零售等合并口径）"）。
4. 图表规格只描述"画什么"（图型、要展示的数据点、标题），不要自己画图或输出图片。
4.0 **`图表规格列表` 给 1~3 项。判断标准是"这条论述用到了几组不同性质的数据"，
   而不是"至少给一张就够了"。** 论述里每摆出一组读者需要看见的数据，就该配一张图。
   典型的一条逻辑往往有 2 组：**板块层面的总量/分位**（gauge、number_cards）
   与**板块内部的个股分布**（bar、bar_line）——这是两件不同的事，各配一张。
   ⚠ 最常被漏掉的是第二类：正文写了"贵州茅台净利同比+1.5%、五粮液+82.6%，
   而山西汾酒 -19.0%、泸州老窖 -19.3%，内部分化严重"，却不配图——
   这正是柱状图最该出场的地方（8 个标签一眼看出分化），只用文字等于浪费了数据。
   **凡正文里罗列了三个及以上同类可比的数（各成分股的净利同比/PB/涨跌幅等），
   就必须为它配一张 `bar`（或 `bar_line`，若同时有两列）。**
   **有"子行业明细"时，各子行业的横向对比图是必须的**——宽口径板块的读者
   首先要看到的就是这张图（哪个子行业强、哪个拖后腿），它比任何合并数字都重要。
   仍然禁止**为了凑数而重复**：同一批数据换个图型再画一遍、
   或把一张图拆成大同小异的两张，都是无效的图。区别在于**数据组是否不同**，
   不在于图型是否不同。
4.1 图型沿用"惯用图类型"，各自的数据点填法：
   - `number_cards`：2~4 个关键指标，每点 {标签, 值}
   - `bar`：同类可比的一组值（如各成分股净利同比），每点 {标签, 值}
   - `line`：**按时间先后**排列的序列（如近几期增速、利率走势），每点 {标签, 值}
   - `bar_line`：**背离类**专用，每点须给两列 {标签, 值, 值2}——
     `值`画柱（如各股区间涨跌幅）、`值2`画折线（如各股净利同比）。
     缺 `值2` 会退化成普通柱状图，等于浪费了这条论证最有力的呈现方式。
   - `gauge`：**分位类**专用（估值/波动率/拥挤度/持仓分位）。渲染成一条历史区间横条，
     标出当前位置与阈值线。每点 {标签, 值, 阈值, 实际值, 区间低, 区间高}：
     `值`填**分位数字本身（0~100，不带%）**，`阈值`填该论点的判定阈值（如 30），
     `实际值`填对应的原始值（如 "1.32倍"），`区间低/区间高`填历史区间两端。
     阈值与区间取不到就省略，只给 `值` 也能画。
     ⚠ `值`填错成原始值（如填 "1.32倍"）会导致整条画不出来——它是百分位不是价格。
   - `two_col`：**两组横向对比**专用（本板块 vs 同业、中外对标）。每点须带 `组` 字段
     标明属于哪一组，如 {组:"本板块", 标签:"证券", 值:"13.9倍"}、
     {组:"同业中位数", 标签:"保险", 值:"18.2倍"}。最多两组。
     可另给 `说明` 作为图下方的一句结论。
4.2 数据点的值**只能来自给你的真实数据**（可用数据/板块全景/成分股明细/研报依据），
   一个都不许编。画不出来就不给图表规格，宁可无图也不要假数据。
5. 核心结论最后综合全部逻辑（含推荐方向），一段话。
5.0 每条逻辑的 `结论` **不印进成品**，它是交给下游产品选择环节（OptionHelper）的输入。
   因此不要复述正文已说过的话（正文写了"高毛利红利期或走向终结"，
   结论再写一遍"红利期或退却"等于同一句说两遍），
   而要把这条逻辑**归结成市场状态的判断**，沿这四个维度讲：
   **方向倾向、时间尺度、波动率状态、风险边界（什么情况下这条判断失效）**。
5.0.1 ⚠ **严禁给出任何具体产品或结构建议。** 挂什么结构、什么期限、买方还是卖方，
   是 OptionHelper 依据实时市场参数决定的事，不是本环节该越权判断的。
   在这里写产品建议有两重危害：一是**越过定价直接给方案**，而我们手上既没有波动率曲面
   也没有报价，说"卖权收益厚"是没有依据的断言；二是下游会把它当输入，
   等于让一个不掌握定价信息的环节替定价环节做了决定。
   **禁止出现**：看涨价差、熊市价差、跨式、宽跨式、鲨鱼鳍、雪球、自动赎回、累购、
   敲入敲出、卖权/买权、买入看涨/看跌、短久期结构 等一切产品与结构名称，
   以及"建议构建…""可考虑参与…""宜采用…"这类操作建议句式。
   × 错："超跌后倾向短久期看涨结构；波动率处极高分位，卖权收益厚但需防继续下行"
   ✔ 对："本轮下跌由情绪驱动而非基本面恶化，20日涨跌幅处近3年3%分位；
        波动率处92%分位、显著高于三年均值；若后续盈利数据继续走弱，
        则超跌属于对基本面的正确定价，这条判断不成立"
5.1 **"各逻辑"里有几条，"逻辑正文"就必须输出几条，一条都不能少、不能留空。**
   逻辑漏写会让成品少掉整块内容。若某条实在缺数据支撑，也要写出来并如实说明
   数据不足，而不是跳过不写。
6. 某条逻辑带"研报依据"时：
   6.1 **必须引用其中"可引用的数字"里的具体数值**，不得只写"估值吸引""需求强劲"
       这类定性描述——那等于浪费了研报里的真数据。
   6.2 数字只能从"可引用的数字"里取，**不得从原文之外引入任何数字**。
   6.3 **不要在正文里写"据某某研报指出""某券商认为"这类字样。** 出处已由成品末尾的
       「数据来源」栏统一列出，正文里再点一遍既啰嗦又像在替第三方背书。
       直接陈述事实与数字即可（"长鑫在通用 DRAM 的全球市占率已突破 7%"）。
   6.4 **必须同时引用该条"可用数据"里的自有数字去印证或补充**，不能只复述研报。
       研报给的是**产业机制**（为什么会这样），我方数据给的是**市场状态**（它正在发生），
       两者合起来才是完整论证。例：研报称"长鑫市占率突破 7%，DRAM 高毛利红利将退却"，
       就该接上我方取到的该板块毛利率或盈利增速实际走势，看是否已现端倪。
       若自有数据与研报判断相悖，按铁律 2.1 如实指出分歧，不得掩饰。
只输出一个 JSON 对象，不要多余文字。"""


def _chart_type(logic_id: str, doc_cats: dict | None = None) -> str:
    """该条论点配什么图 —— 由**论点所属类别**决定（DESIGN §7.3）。

    逻辑id 就是论点库 id（V1/S3/R1…）。论点库文档没有"惯用图类型"列，
    故按类别映射（`thesis._CATEGORY_CHART`）；自由槽 id（free_*）查不到，回落数字卡片。

    研报观点的 id 形如 `doc_21`，同样查不到——但它**有类别**，
    须用 `doc_cats` 换成类别再查，否则整条研报逻辑都会掉进数字卡（实测踩过）。
    """
    from . import thesis as th

    cat = (doc_cats or {}).get(logic_id)
    return th.chart_type_of(cat or logic_id)


def _build_user_prompt(ma: MarketAnalysis) -> str:
    from .planner import DOC_FIELD_PREFIX

    packages = []
    for lw in ma.logics:
        lg = lw.logic
        pkg = {
            "逻辑id": lg.逻辑id,
            "标题": lg.标题,
            "具体论点": lg.具体论点,
            "方向倾向": lg.结构方向倾向,
            "惯用图类型": _chart_type(lg.逻辑id, getattr(ma, "doc_cats", None)),
            "可用数据": [
                {"字段": f.field, "值": f.display or str(f.value)}
                for f in lw.auto if not f.field.startswith(DOC_FIELD_PREFIX)
            ],
            "缺失数据": [f.field for f in lw.gaps],
        }
        # 研报依据单独成块。混在"可用数据"里时实测会被当成背景读读就过——
        # 那里的值都是"1.37倍"这种可直接照抄的短串，而研报原文是一整段话，
        # LLM 无从"原样引用"，结果把 2.6倍/7.0倍 这些真数字全退化成"估值吸引"。
        # 单独列出并显式给出可引用的数字，才用得上。
        cites = [f for f in lw.auto if f.field.startswith(DOC_FIELD_PREFIX)]
        if cites:
            pkg["研报依据_须引用其中数字"] = [
                {"出处": f"{f.source} {f.note}".strip(),
                 "原文": f.display,
                 "可引用的数字": _NUMS.findall(f.display or "")}
                for f in cites
            ]
        packages.append(pkg)
    # 板块全景：摸底取到但没进任何一条逻辑"所需字段"的那些数据。
    # 此前 writer 每条逻辑只看得到自己的 2~3 个触发字段，而摸底实际取了 17 个——
    # PB/分位/ROE/股息率/分红率/波动率全躺在 fv_map 里没传过去，
    # 论述因此只能"两个数字一句话"，撑不起模板那种厚度。
    # 这些值本就在 field_values 里，validator 照常认，不新增溯源风险。
    detail = None
    subs = None
    panorama: dict[str, str] = {}
    for name, fv in (ma.field_values or {}).items():
        if not isinstance(name, str) or name.startswith("__"):
            continue
        if name.startswith(DOC_FIELD_PREFIX) or not getattr(fv, "ok", False):
            continue
        if name == "成分股明细":
            detail = fv.display
            continue
        if name == "子行业明细":
            subs = fv.display
            continue
        panorama[name] = fv.display or str(fv.value)

    # 分析对象必须显式告诉 writer。此前 spec 里只有"主题"，没有板块名与代表标的名，
    # 于是正文通篇写"板块如何如何"却从不说是哪个板块——不是模型偷懒，是它根本不知道。
    sector = (ma.field_values or {}).get("__sector__") or ""
    spec = {
        "主题": ma.plan.主题,
        "分析对象_首次提及须写全称": {
            "板块": sector or "（未指定板块，按主题表述）",
            "代表标的": f"{getattr(ma, 'rep_name', '') or ''}（{ma.rep_code}）".lstrip("（").rstrip(),
        },
        "类型": ma.plan.类型,
        "叙事主轴": ma.plan.叙事主轴,
        "整体方向": ma.plan.整体方向,
        "板块全景数据_可引用以充实论证_勿偏题": panorama,
        # 键名里点明"既可举例也可作图"：此前只写"可用于举例说明分化"，
        # 实测 writer 老老实实只拿它写正文举例，从不据此出图（#66）。
        **({"成分股明细_可举例说明分化_也可直接作bar图": detail} if detail else {}),
        # 宽口径板块才有。给它单独一个键并在铁律 3.4 里点名，
        # 否则合并口径的报告会通篇只讲市值最大的那个子行业（见 #67）。
        **({"子行业明细_本板块由这几个一级行业合并而成_须体现覆盖面": subs} if subs else {}),
        "各逻辑": packages,
        "输出格式": {
            "核心结论": "一段话，最后综合各逻辑，含推荐方向",
            "推荐方向": "看涨|震荡|看跌|中性",
            "逻辑正文": [
                {
                    "逻辑id": "对应输入的逻辑id",
                    "论述": "分析文字，只用可用数据的数字",
                    "图表规格列表": [
                        {
                            "类型": "沿用惯用图类型，或按下方数据形态另选",
                            "标题": "字符串",
                            "数据点": [{"标签": "字段名或说明", "值": "真实值"}],
                            "说明": "可选",
                        }
                    ],
                    "结论": "一句话：这条逻辑对衍生品结构意味着什么（不进正文，供下游定结构）",
                }
            ],
        },
    }
    return json.dumps(spec, ensure_ascii=False, indent=2)


# 输出额度。#44 把每条论述的要求从"简洁"提到"120~200字+论证链条"后，
# 三条逻辑加核心结论、图表规格的输出量翻了几倍，默认额度可能不够——
# 而额度不足的表现恰恰是"漏写几条逻辑"，与模型偷懒难以区分，故显式给足。
_MAX_TOKENS = 8000


def _parse(d: dict, ma: MarketAnalysis, rc: ReportContent) -> list[str]:
    """把 LLM 输出灌进 rc，返回本次的空缺逻辑 id。"""
    rc.核心结论 = str(d.get("核心结论", "")).strip() or rc.核心结论
    rc.推荐方向 = str(d.get("推荐方向", "")).strip() or rc.推荐方向
    got = {lc.逻辑id for lc in rc.logics if lc.论述}
    for it in d.get("逻辑正文", []):
        if not isinstance(it, dict):
            continue
        lid = str(it.get("逻辑id", "")).strip()
        body = str(it.get("论述", "")).strip()
        if lid in got:                       # 重试补回来的，不重复添加
            continue
        specs = it.get("图表规格列表")
        if not isinstance(specs, list):        # 兼容模型偶尔仍给单个对象
            single = it.get("图表规格")
            specs = [single] if isinstance(single, dict) and single else []
        specs = [s for s in specs if isinstance(s, dict) and s][:3]   # 硬上限 3 张
        rc.logics.append(LogicContent(
            逻辑id=lid, 论述=body,
            图表规格列表=specs,
            结论=str(it.get("结论", "")).strip(),
        ))
        if body:
            got.add(lid)

    empty = [lc.逻辑id for lc in rc.logics if not lc.论述]
    missing = {lg.逻辑id for lg in ma.plan.logics} - {lc.逻辑id for lc in rc.logics}
    # 核心结论也算缺口。它不在"逻辑正文"里，此前完全不受漏写检查覆盖——
    # 模型一旦没给（截断或直接省略），成品顶部就是个空的结论框，而 rc.ok 仍为 True，
    # 一路无声地渲染出去（#68 实测撞到：一份 3 条逻辑齐全的报告核心结论整段为空）。
    head = [] if rc.核心结论 else ["核心结论"]
    return head + empty + sorted(missing)


def write(ma: MarketAnalysis, client: DeepSeekClient | None = None) -> ReportContent:
    rc = ReportContent(主题=ma.plan.主题, 类型=ma.plan.类型)
    client = client or DeepSeekClient()
    if not client.available():
        rc.error = "未配置 DeepSeek key"
        return rc

    user = _build_user_prompt(ma)
    res = client.chat_json(_SYSTEM, user, temperature=0.4, max_tokens=_MAX_TOKENS)
    rc.tokens = client.total_tokens
    if not res.ok or not isinstance(res.data, dict):
        rc.error = res.error or "LLM 返回非预期结构"
        return rc

    gaps = _parse(res.data, ma, rc)

    # 漏写自动补一次。实测这是最常见的产出缺陷（#41/#44 各遇到一次），
    # 而它的后果是成品直接少掉整块内容——与其在终端提示"建议重跑"让人工再来一遍，
    # 不如就地只补缺的那几条（不重写已写好的，省 token 也避免已有内容被改坏）。
    if gaps:
        缺结论 = "核心结论" in gaps
        缺逻辑 = [g for g in gaps if g != "核心结论"]
        要求 = []
        if 缺逻辑:
            要求.append(f"遗漏了这些逻辑：{'、'.join(缺逻辑)}，"
                        f"请输出这几条的『逻辑正文』条目（格式同前，同样 120~200 字、要有论证链条）")
        # 补写提示必须按实际缺什么来写。此前无条件写死"核心结论也不必重写"，
        # 于是首轮就没给核心结论时，补写这一轮反而被明确告知别写，缺口永远补不回来。
        if 缺结论:
            要求.append("『核心结论』整段缺失，请补出（一段话，综合各逻辑，含推荐方向），"
                        "并同时给出『推荐方向』字段")
        retry = (f"{user}\n\n【补写要求】上一次输出" + "；".join(要求) +
                 "。其余已写好的不必重复。" +
                 ("" if 缺结论 else "核心结论也不必重写。"))
        res2 = client.chat_json(_SYSTEM, retry, temperature=0.4, max_tokens=_MAX_TOKENS)
        rc.tokens = client.total_tokens
        if res2.ok and isinstance(res2.data, dict):
            gaps = _parse(res2.data, ma, rc)

    # 研报自带的配图数列**覆盖** LLM 自拟的图表规格。
    # 那些数已在 docs 里逐个校验过字面出现在研报原文，比让模型从散文里凑数列可靠得多；
    # 而图比文字更难被读者核对——编造的柱子和真的看起来一模一样，故不给模型这个机会。
    # 研报通道目前每条观点最多挂一个已校验数列，故覆盖后是单元素列表；
    # LLM 自拟的图（若有）舍弃，不与已校验数列混排——避免一真一假拼在一条逻辑下。
    charts = getattr(ma, "doc_charts", None) or {}
    for lc in rc.logics:
        if lc.逻辑id in charts:
            lc.图表规格列表 = [charts[lc.逻辑id]]

    # 系统按字段自动配的历史序列图，**追加**在 LLM 自拟的图之后（#71）。
    # 追加而非覆盖：两张图回答的是不同问题——LLM 那张讲"当前横截面"
    # （各子行业/各成分股怎么分布），自动这张讲"纵向历史"（当前值在三年里的位置）。
    # 一横一纵合起来才说得清一条估值或拥挤度的论证，这也正是 #65 允许多图的本意。
    auto = getattr(ma, "auto_charts", None) or {}
    if auto:
        用过: set[str] = set()
        可挂 = [lc for lc in rc.logics if lc.逻辑id not in charts]   # 研报数列那条不掺别的图

        def _attach(lc, key) -> bool:
            spec = auto.get(key)
            if not spec or key in 用过 or len(lc.图表规格列表) >= 3:
                return False
            if spec.get("标题") in {(s or {}).get("标题") for s in lc.图表规格列表}:
                return False
            lc.图表规格列表.append(spec)
            用过.add(key)
            return True

        # ① 按字段挂：该逻辑用到了哪个字段，就配那个字段的历史序列图
        字段 = {lg.逻辑id: list(lg.所需数据字段 or []) for lg in ma.plan.logics}
        for lc in 可挂:
            for f in 字段.get(lc.逻辑id, []):
                _attach(lc, f)

        # ② 板块结构类的图（成分股散点、子行业分组柱）**不属于任何单条逻辑的字段**，
        #    按①永远挂不上。它们描述的是整个板块的横截面，对哪条逻辑都成立，
        #    故挂给当前配图最少的那条，每份报告各出现一次，不重复也不遗漏。
        for key in ("子行业明细", "成分股明细"):
            if key not in auto or key in 用过 or not 可挂:
                continue
            _attach(min(可挂, key=lambda x: len(x.图表规格列表)), key)

    # 补写后仍缺的，如实标记，绝不代笔编造内容。
    rc.空缺逻辑 = gaps
    rc.ok = True
    return rc


